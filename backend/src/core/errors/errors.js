export function safeMessage(error) {
  if (error?.publicMessage) return error.publicMessage;
  const status = Number(error?.status || error?.response?.status || error?.code);
  if (isNetworkFailure(error)) return 'ระบบไม่สามารถเชื่อมต่อ Google ได้ชั่วคราว กรุณาตรวจอินเทอร์เน็ตแล้วลองใหม่';
  if (error?.code === 'ENOENT') return 'ไม่พบไฟล์ credentials กรุณาตรวจการตั้งค่า';
  if (error?.code === 'APP_CONFIGURATION')
    return 'ตั้งค่าเซิร์ฟเวอร์ไม่ครบ กรุณาตรวจ Environment Variables';
  if (/invalid_grant|invalid_client|private.key|credential/i.test(String(error?.message || '')))
    return 'การยืนยันตัวตน Google ไม่สำเร็จ กรุณาตรวจ credentials และการอนุญาตบัญชี';
  if (/Office file|not supported for this document/i.test(String(error?.message || '')))
    return 'ไฟล์นี้ยังเป็น Excel / Office กรุณาแปลงเป็น Google Sheets';
  if (error?.response || error?.config || error?.name === 'GaxiosError') {
    if (status === 401) return 'ยืนยันตัวตน Google ไม่สำเร็จ กรุณาตรวจ credentials';
    const reasons = error?.response?.data?.error?.errors || error?.errors || [];
    const reason = String(reasons[0]?.reason || error?.response?.data?.error?.status || '').toLowerCase();
    if (status === 403 && ['ratelimitexceeded', 'userratelimitexceeded'].includes(reason))
      return 'ระบบกำลังมีคำขอใช้งานจำนวนมาก กรุณารอสักครู่แล้วลองใหม่';
    if (status === 403 && reason === 'quotaexceeded')
      return 'ระบบใช้งานเกินจำนวนคำขอที่กำหนด กรุณาลองใหม่ภายหลัง';
    if (status === 403)
      return 'ไม่มีสิทธิ์เข้าถึง Google Sheets/Drive กรุณาตรวจ API และสิทธิ์บัญชี';
    if (status === 404) return 'ไม่พบไฟล์ Google กรุณาตรวจ ID และสิทธิ์บัญชี';
    if (status === 429) return 'ระบบกำลังมีคำขอใช้งานจำนวนมาก กรุณารอสักครู่แล้วลองใหม่';
    if ([500, 502, 503, 504].includes(status)) return 'ระบบไม่สามารถให้บริการได้ชั่วคราว กรุณาลองใหม่ภายหลัง';
    return 'ระบบเชื่อมต่อ Google ไม่สำเร็จ กรุณาลองใหม่';
  }
  // These errors are generated by application validation, not Google HTTP responses.
  if (status >= 400 && status < 500 && typeof error?.message === 'string') return error.message;
  return 'เซิร์ฟเวอร์ดำเนินการไม่สำเร็จ กรุณาลองใหม่หรือตรวจการตั้งค่า';
}

export function applicationErrorCode(error, status) {
  if (isNetworkFailure(error)) return 'GOOGLE_API_UNAVAILABLE';
  if (error?.response || error?.config || error?.name === 'GaxiosError') {
    if (status === 429) return 'GOOGLE_API_RATE_LIMIT';
    if (status === 403) {
      const reasons = error?.response?.data?.error?.errors || error?.errors || [];
      const reason = String(reasons[0]?.reason || error?.response?.data?.error?.status || '').toLowerCase();
      if (['ratelimitexceeded', 'userratelimitexceeded', 'quotaexceeded'].includes(reason))
        return 'GOOGLE_API_RATE_LIMIT';
      return 'GOOGLE_API_PERMISSION_DENIED';
    }
    if (status === 401) return 'GOOGLE_API_AUTHENTICATION';
    if ([500, 502, 503, 504].includes(status)) return 'GOOGLE_API_UNAVAILABLE';
    return 'GOOGLE_API_ERROR';
  }
  if (status === 401) return 'UNAUTHORIZED';
  if (status === 403) return 'FORBIDDEN';
  if (status === 404) return 'NOT_FOUND';
  if (status === 400) return 'BAD_REQUEST';
  return status >= 500 ? 'INTERNAL_ERROR' : 'APPLICATION_ERROR';
}

export function isRetryableError(error, status) {
  if (isNetworkFailure(error)) return true;
  if (error?.response || error?.config || error?.name === 'GaxiosError') {
    if ([429, 500, 502, 503, 504].includes(status)) return true;
    const reasons = error?.response?.data?.error?.errors || error?.errors || [];
    return status === 403 && ['ratelimitexceeded', 'userratelimitexceeded', 'quotaexceeded']
      .includes(String(reasons[0]?.reason || '').toLowerCase());
  }
  return false;
}
function isNetworkFailure(error) {
  const transientCodes = new Set([
    'ECONNRESET', 'ETIMEDOUT', 'EAI_AGAIN', 'ECONNREFUSED', 'ENETUNREACH', 'EPIPE',
    'ENOTFOUND', 'UND_ERR_CONNECT_TIMEOUT', 'UND_ERR_SOCKET',
  ]);
  let current = error;
  while (current) {
    if (transientCodes.has(String(current.code || ''))) return true;
    current = current.cause;
  }
  return error?.name === 'TypeError' && /fetch failed|network error/i.test(String(error.message || ''));
}
export function logError(error, context = 'API') {
  const stack = String(error?.stack || '')
    .split('\n')
    .filter((line) => /^\s+at /.test(line))
    .slice(0, 12)
    .join('\n');
  // Never log entire Google errors: they may contain authorization headers and JSON keys.
  console.error(`[${context}]`, {
    message: safeMessage(error),
    type: typeof error?.name === 'string' ? error.name : undefined,
    code: /^[A-Z_0-9]+$/.test(String(error?.code)) ? error.code : undefined,
    causeCode: /^[A-Z_0-9]+$/.test(String(error?.cause?.code)) ? error.cause.code : undefined,
    status: Number(error?.status || error?.response?.status || 500),
    googleReason: String(
      error?.response?.data?.error?.errors?.[0]?.reason || error?.response?.data?.error?.status || '',
    ).replace(/[^a-zA-Z0-9_-]/g, '').slice(0, 80) || undefined,
    stack,
  });
}

export function throwHttpError(status, message) {
  throw Object.assign(new Error(message), { status });
}
