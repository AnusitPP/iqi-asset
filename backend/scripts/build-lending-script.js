import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';

// Share Sheet schemas, categories and allowed values with the Node backend.
const modules = [
  'backend/src/core/lending/schema.js',
  'shared/features/lending/formConstants.js',
  'shared/features/lending/status.js',
  'shared/features/catalog/parser.js',
  'shared/features/catalog/search.js',
];
const root = new URL('../../', import.meta.url);
export async function buildSharedScript() {
  const sources = await Promise.all(modules.map((path) => readFile(new URL(path, root), 'utf8')));
  return (
    '// Generated by npm run build:lending-script; do not edit.\n' +
    sources.map((source) => source.replace(/\bexport /g, '')).join('\n')
  );
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  await writeFile(new URL('apps-script/lending/Shared.gs', root), await buildSharedScript());
}
